import { expect } from '@playwright/test';
import { DatabaseSync } from 'node:sqlite';
import { createHash } from 'node:crypto';
import { copyFile, mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { extname, join, resolve } from 'node:path';
import { seedFixture } from '../support/demo.fixture.ts';
import { catalogSnapshot, connectNative, nativePage, isolatedIdentifier, readIsolatedBuild } from '../support/native-session.mjs';
import { checkEditingJourneys } from './user-journey-editing.mjs';
import { checkBrowsingJourneys } from './user-journey-browsing.mjs';
import { checkMediaJourneys } from './user-journey-media.mjs';

const identifier = isolatedIdentifier('local.jingji.user-journey-audit');
const receipt = await readIsolatedBuild(identifier);
const output = resolve('verification/native-user-journeys');
const mediaDirectory = join(output, 'media');
await mkdir(mediaDirectory, { recursive: true });
const fixture = seedFixture();
fixture.settings.reducedMotion = true;
const originalURLs = new Map();
for (const item of fixture.media) {
  const original = item.src;
  const path = join(mediaDirectory, original.split('/').at(-1));
  await copyFile(resolve(original.slice(1)), path);
  item.sourcePath = path;
  item.src = `http://jingji.localhost/media/${encodeURIComponent(item.id)}`;
  item.size = (await stat(path)).size;
  if (item.id === 'p0') item.sourceRevision = 'journey-version-1';
  originalURLs.set(original, item.src);
}
for (const album of fixture.albums) album.cover = originalURLs.get(album.cover);
for (const model of fixture.models) {
  model.avatar = originalURLs.get(model.avatar);
  model.background = originalURLs.get(model.background);
}
// Posters are regenerated by the native thumbnail pipeline from the registered video.
for (const item of fixture.media.filter(item => item.kind === 'video')) delete item.poster;
const broken = join(mediaDirectory, 'broken.jpg');
await writeFile(broken, 'This disposable file is intentionally not a JPEG.');
fixture.media.push({ id: 'broken', kind: 'image', name: 'broken.jpg', src: 'http://jingji.localhost/media/broken',
  sourcePath: broken, size: (await stat(broken)).size, tags: [], favorite: false, liked: false, rating: 0 });
fixture.albums.push({ ...fixture.albums[0], id: 'broken-album', name: '损坏文件回归', mediaIds: ['broken'],
  cover: 'http://jingji.localhost/media/broken', modelIds: [], favorite: false });
const auditedMedia = [...fixture.media];
const hashes = async () => Object.fromEntries(await Promise.all(auditedMedia.map(async item =>
  [item.id, createHash('sha256').update(await readFile(item.sourcePath)).digest('hex')])));
const originalHashes = await hashes();
// SQLite identifies originals by unique path. Distinct test IDs need distinct
// copied files, and every copy stays inside this audit's disposable directory.
async function createAuditMedia(image, prefix, count) {
  if (!/^[a-z0-9-]+$/.test(prefix) || count < 1 || count > 300)
    throw Error('Invalid isolated media request');
  const source = resolve(image.sourcePath);
  if (!source.startsWith(`${mediaDirectory}\\`)) throw Error('Audit source escaped its media directory');
  const media = [];
  const auditDB = new DatabaseSync(join(process.env.APPDATA, identifier, 'catalog.sqlite3'));
  try {
    for (let index = 0; index < count; index++) {
      const id = `${prefix}-${index}`;
      const sourcePath = join(mediaDirectory, `${id}${extname(source)}`);
      await copyFile(source, sourcePath);
      const item = { ...image, id, sourcePath, name: `${id}${extname(source)}`,
        src: `http://jingji.localhost/media/${id}`, favorite: false, tags: [] };
      auditDB.prepare('INSERT OR IGNORE INTO authorized(path) VALUES(?)')
        .run(sourcePath.replaceAll('\\', '/').toLowerCase());
      auditedMedia.push(item);
      originalHashes[id] = createHash('sha256').update(await readFile(sourcePath)).digest('hex');
      media.push(item);
    }
  } finally { auditDB.close(); }
  return media;
}
const formalPath = join(process.env.APPDATA, 'local.jingji.desktop', 'catalog.sqlite3');
const formal = existsSync(formalPath) ? new DatabaseSync(formalPath, { readOnly: true }) : null;
const formalBefore = formal ? catalogSnapshot(formal) : null;
const formalUnchanged = () => formal ? catalogSnapshot(formal) === formalBefore : !existsSync(formalPath);
const browser = await connectNative('http://127.0.0.1:9266', identifier);
const page = nativePage(browser);
const invoke = (command, args = {}) => page.evaluate(({ command, args }) =>
  window.__TAURI_INTERNALS__.invoke(command, args), { command, args });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const checks = {};
const executableHash = receipt.ExecutableHash;
const frontendEntry = receipt.FrontendEntry;
let failure;
try {
  expect(await invoke('plugin:app|identifier')).toBe(identifier);
  expect(frontendEntry).toBeTruthy();
  expect(await page.locator('script[type="module"]').getAttribute('src')).toBe(frontendEntry);
  for (const [name, check] of Object.entries({ editing: checkEditingJourneys, browsing: checkBrowsingJourneys, media: checkMediaJourneys })) {
    await page.goto('http://tauri.localhost/#/settings');
    await expect(page.getByRole('heading', { name: '设置', exact: true })).toBeVisible();
    await invoke('catalog_reset', { seed: fixture });
    // Register only these disposable synthetic paths in this audit's own database.
    // Native file-picker interaction is separately covered by the adapter tests.
    const auditDB = new DatabaseSync(join(process.env.APPDATA, identifier, 'catalog.sqlite3'));
    try {
      for (const { source } of auditDB.prepare("SELECT source FROM entities WHERE kind='media'").all())
        auditDB.prepare('INSERT OR IGNORE INTO authorized(path) VALUES(?)').run(source);
    } finally { auditDB.close(); }
    await page.reload();
    await expect(page.getByRole('heading', { name: '设置', exact: true })).toBeVisible();
    checks[name] = await check(page, invoke, createAuditMedia);
    await page.screenshot({ path: join(output, `${name}.png`) });
    console.log(`${name} user journeys passed`);
  }
  expect(await hashes()).toEqual(originalHashes);
  expect(formalUnchanged()).toBe(true);
  expect(errors).toEqual([]);
} catch (error) { failure = error; throw error; }
finally {
  try {
    const afterHashes = await hashes();
    const originalMediaUnchanged = JSON.stringify(afterHashes) === JSON.stringify(originalHashes);
    const formalCatalogUnchanged = formalUnchanged();
    const report = { engine: 'isolated Release Windows WebView2', identifier, executableHash, frontendEntry, checks, errors,
      failure: failure?.stack, originalMediaUnchanged, formalCatalogUnchanged,
      limits: 'Synthetic originals; delayed/failed writes are injected ahead of real native persistence. IME uses composition events. OS file-picker and Windows IME candidate windows are not automated here.' };
    await writeFile(join(output, 'results.json'), JSON.stringify(report, null, 2));
    console.log(JSON.stringify(report, null, 2));
    expect(originalMediaUnchanged).toBe(true);
    expect(formalCatalogUnchanged).toBe(true);
  } finally { formal?.close(); await browser.close(); }
}
