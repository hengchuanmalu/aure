test('model index fades on demand and filters initials, including Chinese names and scrollable large groups', async ({ page }) => {
  await page.addInitScript(() => {
    const db = JSON.parse(localStorage.getItem('jingji.mock.v1')!);
    const template = db.models[0];
    db.models = Array.from({ length: 60 }, (_, i) => ({ ...template, id: `index-${i}`, name: `Alice ${String(i).padStart(2, '0')}`, alias: '' }));
    db.models.push({ ...template, id: 'z', name: '张三', alias: '' });
    localStorage.setItem('jingji.mock.v1', JSON.stringify(db));
  });
  await page.goto('/#/models');
  const index = page.locator('.model-index');
  await expect(index.getByRole('button', { name: '显示全部模特', exact: true })).toHaveCount(0);
  await page.mouse.move(700, 100);
  await expect(index).toHaveCSS('opacity', '0');
  await page.locator('.model-index-zone').hover();
  await expect(index).toHaveCSS('opacity', '1');
  const indexBox = await index.boundingBox();
  const addBox = await page.locator('.topbar').getByRole('button', { name: '添加模特', exact: true }).boundingBox();
  expect(indexBox!.y).toBeGreaterThan(addBox!.y + addBox!.height);
  expect(indexBox!.y).toBeLessThan(160);
  await page.getByRole('button', { name: '筛选 Z 开头的模特', exact: true }).click();
  await expect(page.getByRole('link', { name: /张三/ })).toBeVisible();
  await expect(page.locator('[data-model-initial]')).toHaveCount(1);
  await expect(page.locator('[data-model-initial="A"]')).toHaveCount(0);
  await page.mouse.move(700, 100);
  await expect(index).toHaveCSS('opacity', '0');
  await page.keyboard.press('Tab');
  await page.getByRole('group', { name: '显示模特字母索引' }).focus();
  await page.getByRole('button', { name: '筛选 A 开头的模特', exact: true }).focus();
  await expect(index).toHaveCSS('opacity', '1');
  await page.keyboard.press('Enter');
  await expect(page.getByRole('button', { name: '筛选 A 开头的模特', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('[data-model-initial="Z"]')).toHaveCount(0);
  await expect(page.locator('.models-grid')).toHaveAttribute('data-total-items', '60');
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight));
  await expect(page.getByRole('link', { name: /Alice 59/ })).toBeVisible();
  const scrolledIndexBox = await index.boundingBox();
  expect(scrolledIndexBox!.y).toBeCloseTo(indexBox!.y, 0);
  await page.locator('.page-heading h1').click();
  await expect(page.locator('.models-grid')).toHaveAttribute('data-total-items', '61');
  await page.locator('.model-index-zone').hover();
  await page.getByRole('button', { name: '筛选 Z 开头的模特', exact: true }).click();
  await page.getByRole('button', { name: '显示全部模特', exact: true }).focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('.models-grid')).toHaveAttribute('data-total-items', '61');
  await expect(page.locator('.picker-pages')).toHaveCount(0);
  await expect(page.getByRole('textbox', { name: '搜索模特', exact: true })).toHaveCount(0);
  await expect(page.locator('.page-heading p')).toHaveCount(0);
  await expect(page.getByRole('button', { name: '添加模特', exact: true })).toHaveCount(1);
  await page.getByRole('button', { name: '添加模特', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByLabel('模特名称', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
});

test('clicking blank model-page space clears the index filter while controls and cards keep their actions', async ({ page }) => {
  await page.addInitScript(() => {
    const db = JSON.parse(localStorage.getItem('jingji.mock.v1')!);
    db.models = [{ ...db.models[0], id: 'blank-a', name: 'Alice' }, { ...db.models[0], id: 'blank-z', name: '张三' }];
    localStorage.setItem('jingji.mock.v1', JSON.stringify(db));
  });
  await page.goto('/#/models');
  const zone = page.locator('.model-index-zone');
  const filter = async (letter: string) => {
    await zone.hover();
    await page.getByRole('button', { name: `筛选 ${letter} 开头的模特`, exact: true }).click();
    await expect(page.locator('[data-model-initial]')).toHaveCount(1);
  };
  await filter('Z');
  await page.getByRole('combobox', { name: '搜索写真、模特或标签', exact: true }).click();
  await expect(page.locator('[data-model-initial="Z"]')).toHaveCount(1);
  await page.locator('.topbar').getByRole('button', { name: '添加模特', exact: true }).click();
  const editor = page.getByRole('dialog', { name: '添加模特', exact: true });
  await expect(editor).toBeVisible();
  await editor.getByRole('button', { name: '取消', exact: true }).click();
  await expect(editor).toHaveCount(0);
  await expect(page.locator('[data-model-initial="Z"]')).toHaveCount(1);
  const content = page.locator('#main-content');
  const box = await content.boundingBox();
  await content.click({ position: { x: box!.width / 2, y: box!.height - 30 } });
  await expect(page.locator('[data-model-initial]')).toHaveCount(2);
  await expect(page.locator('.model-index button[aria-pressed="true"]')).toHaveCount(0);
  await filter('A');
  await page.getByRole('link', { name: /Alice/ }).click();
  await expect(page).toHaveURL(/#\/models\/blank-a$/);
  await expect(page.getByRole('heading', { level: 1, name: 'Alice', exact: true })).toBeVisible();
});
