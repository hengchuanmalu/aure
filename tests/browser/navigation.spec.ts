test('tags owns management, settings removes the entry, and sidebar order persists after long press', async ({ page }) => {
  await page.goto('/#/library');
  const nav = page.getByRole('navigation', { name: '主导航' });
  const settings = nav.getByRole('link', { name: '设置', exact: true });
  await expect(settings).toHaveClass(/nav-settings-last/);
  for (const width of [1440, 900, 480]) {
    await page.setViewportSize({ width, height: 960 });
    const box = (await settings.boundingBox())!;
    expect(Math.abs(960 - box.y - box.height - 14)).toBeLessThan(1);
  }
  await page.setViewportSize({ width: 1440, height: 960 });
  await expect(nav.getByRole('link', { name: '收藏', exact: true })).toBeVisible();
  await nav.getByRole('link', { name: '标签', exact: true }).click();
  await expect(page).toHaveURL(/#\/tags$/);
  await expect(page.getByRole('group', { name: '标签筛选', exact: true })).toBeVisible();
  await expect(nav.locator('a[title]')).toHaveCount(0);
  await nav.getByRole('link', { name: '设置', exact: true }).click();
  await expect(page.locator('.settings-page').getByRole('heading', { name: '标签', exact: true })).toHaveCount(0);
  await expect(page.locator('.settings-page a[href*="tags"]')).toHaveCount(0);
  await nav.getByRole('link', { name: '标签', exact: true }).click();
  await expect(page.locator('.library-toolbar').getByRole('button', { name: /^筛选/ })).toHaveCount(0);
  await page.goto('/#/tags/manage');
  await expect(page).toHaveURL(/tags\/manage/);
  await expect(page.locator('h1')).toHaveText('标签');
  await expect(nav.getByRole('link', { name: '标签', exact: true })).toHaveClass(/active/);
  await expect(nav.getByRole('link', { name: '设置', exact: true })).not.toHaveClass(/active/);
  await page.goto('/#/tags');
  await expect(page).toHaveURL(/#\/tags$/);
  const source = await nav.getByRole('link', { name: '模特', exact: true }).boundingBox();
  const target = await nav.getByRole('link', { name: '发现', exact: true }).boundingBox();
  await page.mouse.move(source!.x + 20, source!.y + 25);
  await page.mouse.down();
  await page.waitForTimeout(460);
  await page.mouse.move(target!.x + 20, target!.y + 25, { steps: 8 });
  await page.mouse.up();
  await expect(nav.locator('a').first()).toHaveText('模特');
  await expect(page).toHaveURL(/#\/tags$/);
  await page.reload();
  await expect(nav.locator('a').first()).toHaveText('模特');
  await nav.locator('a').first().focus();
  await page.keyboard.press('Alt+ArrowDown');
  await expect(nav.locator('a').nth(1)).toHaveText('模特');
});

